//! ## 这个系统是什么
//!
//! 订单簿(order book)是交易所最核心的那个数据结构:所有还没成交的挂单
//! 按价格排好队,新来一笔单子就看它能不能和对面的单子撮合上。
//! 「最优买价 / 最优卖价 / 买卖价差」这些行情数字,全都是从它身上读出来的。
//!
//! ## 管道全貌
//!
//! ```text
//!                    ┌──────────────────────────────────┐
//!   Order  ─submit─▶ │            OrderBook             │ ─▶ Vec<Trade>
//!  (一笔单子)         │                                  │    (成交回报)
//!                    │   bids: 买盘 ──┐                  │
//!                    │               ├─ 按价格分档       │
//!                    │   asks: 卖盘 ──┘  档位内按时间排队 │
//!                    └──────────────────────────────────┘
//!                                    │
//!                            吃不完的剩余量挂回簿子
//!
//!   阶段 1        阶段 2 + 3            阶段 4          阶段 5
//!   ────────      ──────────────        ────────        ────────
//!   Price/Qty     档位容器选型          insert          撮合
//!   Order/Trade   BookSide<K: Ord>      cancel          价格穿越
//!   的类型建模    (泛型:一份代码
//!                  服务买卖两边)
//! ```
