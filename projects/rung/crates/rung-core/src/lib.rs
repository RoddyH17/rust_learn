//! # rung-core —— 限价订单簿的类型与容器层
//!
//! Rung 的最底层。这一层**不知道撮合规则是什么** —— 它只提供
//! 「价格」「数量」「订单」「档位」「一侧簿子」这些概念,以及它们的容器。
//! 撮合规则住在 `rung-match`。
//!
//! ## 架构约束(不是风格,是硬规矩)
//!
//! - **零依赖**:`Cargo.toml` 的 `[dependencies]` 必须永远是空的
//! - **零 I/O**:不碰网络、文件、标准输出
//! - **零非确定性**:不读系统时钟、不用随机数、不依赖 `HashMap` 的迭代顺序
//!
//! 前两条由编译和 code review 保证;第三条会在阶段 9 被「同一份日志重放两次
//! 必须逐字节相同」这条测试正面检验。
//!
//! ## 为什么这些约束值钱
//!
//! 交易所的撮合内核必须**公平**,而公平要求**确定性**:同一批订单,
//! 不管跑多少次、在哪台机器上跑,结果必须一样。任何副作用都会破坏它。
//! 详见 `PRIMER.md` §6。
//!
//! ## 当前进度
//!
//! | 阶段 | 内容 | 状态 |
//! |---|---|---|
//! | 1 | `Price` / `Qty` / `Side` / `Order` | 🔨 进行中 |
//! | 2 | `PriceLevel` 档位内 FIFO | ⏸ |
//! | 3 | `BookSide<K: Ord>` 泛型服务买卖两边 | ⏸ |
//! | 4 | `OrderBook` 索引与撤单 | ⏸ |
//!
//! ## 用法
//!
//! ```
//! use rung_core::{Price, Qty, Side, Order};
//!
//! let o = Order::new(1, Side::Buy, Price::from_ticks(1005), Qty::new(100));
//! assert_eq!(o.price.to_string(), "10.05");
//! assert_eq!(o.side.opposite(), Side::Sell);
//! ```

