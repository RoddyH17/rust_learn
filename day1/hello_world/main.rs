// Day 1 — 最简单的 Rust 程序
//
// 编译:rustc main.rs   (rustc 是 Rust 的编译器,把源代码变成可执行文件)
// 运行:./main
//
// "编译"就是把人能读的代码翻译成电脑能直接执行的程序。
// 之后我们会改用 cargo 来管理项目,rustc 裸编译只是为了理解底层发生了什么。

fn main() {
    // fn 定义一个函数;main 是程序的入口——运行程序时从这里开始执行
    // println! 用来往屏幕上打印一行字
    // 名字带 ! 说明它是"宏"(macro),暂时只需要记住:调用宏要写 !
    println!("Hello, world!");
}
